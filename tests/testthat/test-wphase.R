# Windowed phase synchrony (wphase) — oracle + contract tests.
#
# PLV formula source: lachaux1999 (p. 195) — PLV = (1/N) |sum_n exp(j theta_n)|
# where theta is the phase difference; see cairn/references/lachaux1999.md.
# bsync adaptation: single-trial, averaged over time samples within a sliding
# window at a lag offset (documented in the reference note and roxygen).

# Helper: wrapped circular difference in (-pi, pi] ----------------------------
wrap_diff <- function(a, b) {
  d <- (a - b + pi) %% (2 * pi) - pi
  # %% maps an exact multiple of 2*pi to -pi; fold that edge case back to pi
  ifelse(d <= -pi, d + 2 * pi, d)
}

# Closed-form oracle (Layer 1 / doctrine type: closed-form) -------------------
#
# For x[t] = cos(w1*t + a), y[t] = cos(w2*t + b), t = 0..n-1, with w1 and w2
# integer-cycle frequencies (w = 2*pi*k/n, 0 < k < n/2), the discrete analytic
# signal is exactly exp(i*(w*t + phase)), so the Hilbert phases are exactly
# w1*t + a and w2*t + b. Phase difference across a window of size w at any
# start/lag advances by dw = w1 - w2 per sample, so
#   PLV = |sum_{k=0}^{w-1} exp(i*dw*k)| / w = |sin(w*dw/2)| / (w*|sin(dw/2)|)
# (the Dirichlet kernel), identical for every window and lag.
#
# Fixture arithmetic (n = 64, k1 = 8, k2 = 6, window_size = 16):
#   w1 = 2*pi*8/64 = pi/4,  w2 = 2*pi*6/64 = 3*pi/16,  dw = pi/16
#   w*dw/2 = 16*(pi/16)/2 = pi/2, so sin(w*dw/2) = 1
#   sin(dw/2) = sin(pi/32) = 0.0980171403...
#   PLV = 1 / (16 * 0.0980171403) = 0.6376435773...
test_that("closed-form oracle: Dirichlet-kernel PLV on integer-cycle cosines (lachaux1999 p. 195)", {
  n <- 64
  t <- 0:(n - 1)
  a <- 0.7
  b <- 0.2
  x <- cos(2 * pi * 8 * t / n + a)
  y <- cos(2 * pi * 6 * t / n + b)

  res <- wphase(x, y, window_size = 16, lag_max = 1)

  plv_expected <- abs(sin(16 * (pi / 16) / 2)) / (16 * abs(sin((pi / 16) / 2)))
  # = 1 / (16 * sin(pi/32)) = 0.637643577350...
  expect_true(all(abs(res$results_df$plv - plv_expected) < 1e-8))

  # rel_phase for the first grid row (i = 2, tau = -1..1): with 1-based series
  # index idx, phi_x[idx] = w1*(idx-1) + a, phi_y[idx+tau] = w2*(idx+tau-1) + b.
  # Circular-mean angle over the window = base + dw*(w-1)/2 where
  # base = w1*(i-1) - w2*(i+tau-1) + (a-b). For i = 2, tau = 0:
  #   base = pi/4 - 3*pi/16 + 0.5 = pi/16 + 0.5
  #   rel  = pi/16 + 0.5 + (pi/16)*7.5 = 0.5 + 8.5*pi/16 = 2.16897...
  row1 <- res$results_df[res$results_df$tau == 0, ][1, ]
  rel_expected <- 0.5 + 8.5 * pi / 16
  expect_true(abs(wrap_diff(row1$rel_phase, rel_expected)) < 1e-8)
})

# Analytic check: identical-frequency sinusoids -> PLV = 1, offset recovered --
test_that("analytic check: fixed phase offset yields PLV ~ 1 and recovers the offset", {
  n <- 128
  t <- 0:(n - 1)
  offset <- 0.9
  x <- cos(2 * pi * 8 * t / n + offset)
  y <- cos(2 * pi * 8 * t / n)

  res <- wphase(x, y, window_size = 32, lag_max = 2)
  tau0 <- res$results_df[res$results_df$tau == 0, ]

  expect_true(all(abs(tau0$plv - 1) < 1e-6))
  expect_true(all(abs(wrap_diff(tau0$rel_phase, offset)) < 1e-6))
})

# Live oracle (doctrine type: live; depth, not bar-clearing — shares
# gsignal::hilbert with the shipped path, so it validates the windowed PLV
# arithmetic, not phase extraction) -------------------------------------------
test_that("live oracle: dumb pure-R windowed PLV matches the shipped path on sim_dyad", {
  x <- sim_dyad$z_A[1:300]
  y <- sim_dyad$z_B[1:300]

  res <- wphase(x, y,
    window_size = 64, lag_max = 8,
    window_increment = 5, lag_increment = 3
  )

  # Deliberately dumb recomputation: explicit loops over hilbert phases.
  phi_x <- Arg(gsignal::hilbert(x))
  phi_y <- Arg(gsignal::hilbert(y))
  w <- 64
  for (r in seq_len(nrow(res$results_df))) {
    i <- res$results_df$i[r]
    tau <- res$results_df$tau[r]
    dphi <- phi_x[i:(i + w - 1)] - phi_y[(i + tau):(i + tau + w - 1)]
    plv_ref <- Mod(mean(exp(1i * dphi)))
    rel_ref <- Arg(mean(exp(1i * dphi)))
    expect_true(abs(res$results_df$plv[r] - plv_ref) < 1e-8)
    expect_true(abs(wrap_diff(res$results_df$rel_phase[r], rel_ref)) < 1e-8)
  }
})

# Simulated-null bound (frozen; generator: data-raw/wphase_null_bound.R) ------
test_that("white-noise PLV stays below the committed simulated-null q99", {
  # Frozen null quantile: q99 of mean_plv over 500 independent white-noise
  # pairs (n = 600, window_size = 96, lag_max = 10, window_increment = 4,
  # lag_increment = 2), master seed 20260829 — generated by
  # data-raw/wphase_null_bound.R (committed; reproduces this value).
  null_q99 <- 0.1316320

  vals <- vapply(1:5, function(seed) {
    set.seed(seed)
    wphase(rnorm(600), rnorm(600),
      window_size = 96, lag_max = 10,
      window_increment = 4, lag_increment = 2
    )$aggregate[["mean_plv"]]
  }, numeric(1))
  # The mean of five independent null draws sits far below the single-draw
  # q99, so this discriminates inflation without the ~5% per-run flake a
  # per-draw q99 comparison would carry (P(any of 5 draws > q99) ~ 1-.99^5).
  expect_lt(mean(vals), null_q99)
})

# AC1: contract — grid geometry, Invariants 4/7/8 -----------------------------
test_that("realized window count and lag set match hand-computed expectations", {
  # n_r = floor((n - w_max - 2*lag_max) / w_inc), w_max = window_size - 1.
  cases <- list(
    # window_size odd, increments 1: n = 100, w_max = 30, n_r = 100-30-10 = 60
    list(n = 100, ws = 31, wi = 1, lm = 5, li = 1, n_r = 60, lags = -5:5),
    # window_size even, window_increment 3: floor((120-39-16)/3) = 21
    list(n = 120, ws = 40, wi = 3, lm = 8, li = 1, n_r = 21, lags = -8:8),
    # lag_increment 3 (asymmetric truncation): seq(-5, 5, 3) = -5 -2 1 4
    list(
      n = 100, ws = 31, wi = 2, lm = 5, li = 3,
      n_r = 30, lags = c(-5L, -2L, 1L, 4L)
    )
  )
  for (cs in cases) {
    set.seed(1)
    res <- wphase(rnorm(cs$n), rnorm(cs$n),
      window_size = cs$ws, window_increment = cs$wi,
      lag_max = cs$lm, lag_increment = cs$li
    )
    expect_equal(length(unique(res$results_df$i)), cs$n_r)
    expect_equal(sort(unique(res$results_df$tau)), sort(cs$lags))
    expect_equal(nrow(res$results_df), cs$n_r * length(cs$lags))
  }
})

