# AC5: NA policy — abort with guidance ----------------------------------------
test_that("wphase aborts on NA-containing input with imputation guidance", {
  set.seed(4)
  n <- 100
  base_x <- rnorm(n)
  base_y <- rnorm(n)

  na_cases <- list(
    x_interior = {
      x <- base_x
      x[50] <- NA
      list(x = x, y = base_y)
    },
    y_interior = {
      y <- base_y
      y[50] <- NA
      list(x = base_x, y = y)
    },
    x_leading = {
      x <- base_x
      x[1] <- NA
      list(x = x, y = base_y)
    },
    x_trailing = {
      x <- base_x
      x[n] <- NA
      list(x = x, y = base_y)
    },
    x_all = list(x = rep(NA_real_, n), y = base_y)
  )

  time_na <- c(NA_real_, seq_len(n - 1))
  expect_error(
    wphase(base_x, base_y, time = time_na, window_size = 31, lag_max = 5),
    regexp = "impute_ts_gaps"
  )

  for (case in na_cases) {
    expect_error(
      wphase(case$x, case$y, window_size = 31, lag_max = 5),
      regexp = "impute_ts_gaps"
    )
  }
})

